const fs = require('node:fs'), vm = require('node:vm'), assert = require('node:assert/strict');
const html = fs.readFileSync('index.html','utf8');
for (const match of html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)) new vm.Script(match[1]);
const source = html.slice(html.indexOf('function updateCheckoutSummary()'), html.indexOf('async function applyCoupon()'));
const elements = Object.fromEntries(['summarySubtotal','summaryCouponRow','summaryCouponDiscount','summaryTotal'].map(id => [id,{style:{},textContent:''}]));
const context = vm.createContext({document:{getElementById:id=>elements[id]},cart:[{price:98,qtd:1}],appliedCoupon:{tipo:'percentual',desconto_percentual:20,valor_minimo:50}});
vm.runInContext(source,context);
vm.runInContext('updateCheckoutSummary()',context);
assert.equal(elements.summaryCouponDiscount.textContent,'- R$ 19,60');
assert.equal(elements.summaryTotal.textContent,'R$ 78,40');
vm.runInContext('cart[0].qtd=2; updateCheckoutSummary()',context);
assert.equal(elements.summaryCouponDiscount.textContent,'- R$ 39,20');
assert.equal(elements.summaryTotal.textContent,'R$ 156,80');
vm.runInContext('cart[0].price=30; cart[0].qtd=1; updateCheckoutSummary()',context);
assert.equal(elements.summaryCouponRow.style.display,'none');
const panel = fs.readFileSync('assets/panel.js','utf8');
assert.ok(panel.includes('Desconto (%)'));
assert.ok(panel.includes('min="0.01" max="100" step="0.01"'));
assert.ok(!panel.includes('discountInput?.addEventListener'));
console.log('PASS: inline JavaScript syntax, checkout percentage recalculation, minimum order and percentage form constraints.');
